def dashboard(income, expenses, result, scenarios, score_result):

    fig, axes = plt.subplots(1, 3, figsize=(16, 5))

    fig.suptitle(
        'Family Financial Health Dashboard',
        fontsize=16,
        fontweight='bold'
    )

    # ------------------------------
    # CHART 1 — EXPENSE BREAKDOWN
    # ------------------------------

    labels = []
    values = []

    for category, amount in expenses.items():
        if amount > 0:
            labels.append(category)
            values.append(amount)

    axes[0].pie(
        values,
        labels=labels,
        autopct='%1.0f%%',
        startangle=90
    )

    axes[0].set_title('Expense Breakdown')

    # ------------------------------
    # CHART 2 — INCOME VS EXPENSES
    # ------------------------------

    total_expenses = result['total_exp']
    surplus = result['surplus']

    categories = ['Income', 'Expenses', 'Surplus']
    amounts = [income, total_expenses, max(surplus, 0)]

    axes[1].bar(categories, amounts)

    axes[1].set_title('Monthly Financial Position')
    axes[1].set_ylabel('Amount (₹)')

    # ------------------------------
    # CHART 3 — 5-YEAR COMPOUNDING
    # ------------------------------

    r = 0.07 / 12
    months = list(range(61))

    for label, monthly in scenarios:
      curve = [
        monthly * ((1 + r) ** m - 1) / r
        for m in months
    ]

    axes[2].plot(
        months,
        curve,
        label=label,
        marker='o',
        markevery=12
    )

    final_value = curve[-1]

    axes[2].annotate(
        f'₹{final_value:,.0f}',
        xy=(60, final_value),
        xytext=(-5, 8),
        textcoords='offset points',
        fontsize=8
    )

    axes[2].set_xlabel('Months')
    axes[2].set_ylabel('Projected Value (₹)')
    axes[2].set_title('5-Year Compounding')
    axes[2].legend(fontsize=8)


    # ------------------------------
    # FINANCIAL HEALTH SCORE
    # ------------------------------

    score = score_result['score']
    category = score_result['category']

    fig.text(
        0.5,
        0.01,
        f'Financial Health Score: {score}/100 — {category}',
        ha='center',
        fontsize=13,
        fontweight='bold'
    )

    plt.tight_layout(rect=[0, 0.05, 1, 0.95])

    plt.savefig(
        'family_ledger_dashboard.png',
        dpi=150,
        bbox_inches='tight'
    )

    plt.show()

    print('\nDashboard saved as family_ledger_dashboard.png')

