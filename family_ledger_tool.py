def compound(monthly, years=5, annual_rate=0.07):
  r = annual_rate / 12
  n = years * 12
  return monthly * ((1 + r) ** n - 1) / r

def project_savings(monthly_savings, result):
    potential = result['potential_monthly_saving']
    discretionary = result['discretionary']
    discretionary_pct = result['discretionary_pct']

    scenarios = []
         # Scenario 1 — Current savings
    if monthly_savings > 0:
        scenarios.append(
            ('Current savings', monthly_savings)
        )
         # Scenario 2 — Current savings + 10% variable reduction
        moderate = monthly_savings + potential

        scenarios.append(
            ('+ 10% variable reduction', moderate)
        )
        # Scenario 3 — Optimised scenario
        if discretionary_pct > 20:
            discretionary_reduction = discretionary * 0.15
            optimised = (
                monthly_savings
                + potential
                + discretionary_reduction
            )
            scenarios.append(
                ('Optimised scenario', optimised)
            )
    else:
        # No current savings provided
        scenarios.append(
            ('Illustrative: 10% variable reduction', potential)
        )

        # Additional scenario if discretionary spending is above 20%
        if discretionary_pct > 20:
            discretionary_reduction = discretionary * 0.15
            optimised = potential + discretionary_reduction
            scenarios.append(
                ('Illustrative: variable + discretionary reduction',
                 optimised)
            )
    print("\n=== 5-YEAR COMPOUNDING PROJECTION ===")
    print("Assumed annual return: 7%")
    print("Projection period: 5 years")
    if monthly_savings == 0:
        print("Current monthly savings were not provided.")
        print("The projection is illustrative.")
    for label, monthly in scenarios:
        fv = compound(monthly)
        print(
            f"\n{label}:"
            f"\n  ₹{monthly:,.0f}/month"
            f" → ₹{fv:,.0f} after 5 years"
        )
    return scenarios

