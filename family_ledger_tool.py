def analyse (income,expenses):
  total_exp = sum(expenses.values())
  surplus = income-total_exp
  remaining_pct = (surplus / income * 100) if income else 0
  expense_pct = (total_exp / income * 100) if income else 0

  fixed = (expenses['Housing (rent/EMI)'] +
         expenses['Education fees'] +
         expenses['Insurance/LIC'] +
         expenses['Loan EMIs'])

  variable = (expenses['Food & groceries'] +
                expenses['Utilities'] +
                expenses['Transport'] +
                expenses['Mobile & internet'] +
                expenses['Medical'])

  discretionary = (expenses['Clothing'] +
                expenses['Entertainment'])

  fixed_pct = (fixed / income * 100) if income else 0
  variable_pct = (variable / income * 100) if income else 0
  discretionary_pct = (discretionary / income * 100) if income else 0

  potential_monthly_saving = variable * 0.10
  potential_annual_saving = potential_monthly_saving * 12

  return {
        'income': income,
        'total_exp': total_exp,
        'surplus': surplus,
        'remaining_pct': remaining_pct,
        'expense_pct' : expense_pct,
        'fixed': fixed,
        'variable': variable,
        'discretionary': discretionary,
        'fixed_pct': fixed_pct,
        'variable_pct': variable_pct,
        'discretionary_pct': discretionary_pct,

        'potential_monthly_saving': potential_monthly_saving,
        'potential_annual_saving': potential_annual_saving,
    }

