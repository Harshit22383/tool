def financial_health_score(income, result):

    surplus = result['surplus']
    expense_pct = result['expense_pct']
    discretionary_pct = result['discretionary_pct']
    potential_saving = result['potential_monthly_saving']

    # ------------------------------
    # 1. SURPLUS / DEFICIT — 25 POINTS
    # ------------------------------

    if surplus <= 0:
        surplus_score = 0
    else:
        surplus_pct = (surplus / income) * 100

        if surplus_pct >= 30:
            surplus_score = 25
        elif surplus_pct >= 20:
            surplus_score = 20
        elif surplus_pct >= 10:
            surplus_score = 15
        elif surplus_pct >= 5:
            surplus_score = 10
        else:
            surplus_score = 5

    # ------------------------------
    # 2. SAVINGS RATE — 25 POINTS
    # ------------------------------

    savings_rate = (surplus / income) * 100

    if savings_rate <= 0:
        savings_score = 0
    elif savings_rate >= 30:
        savings_score = 25
    elif savings_rate >= 20:
        savings_score = 20
    elif savings_rate >= 10:
        savings_score = 15
    elif savings_rate >= 5:
        savings_score = 10
    else:
        savings_score = 5

    # ------------------------------
    # 3. EXPENSE BURDEN — 20 POINTS
    # ------------------------------

    if expense_pct <= 60:
        expense_score = 20
    elif expense_pct <= 70:
        expense_score = 17
    elif expense_pct <= 80:
        expense_score = 14
    elif expense_pct <= 90:
        expense_score = 8
    elif expense_pct <= 100:
        expense_score = 4
    else:
        expense_score = 0

    # ------------------------------
    # 4. SPENDING STRUCTURE — 15 POINTS
    # ------------------------------

    if discretionary_pct <= 10:
        discretionary_score = 15
    elif discretionary_pct <= 15:
        discretionary_score = 12
    elif discretionary_pct <= 20:
        discretionary_score = 9
    elif discretionary_pct <= 30:
        discretionary_score = 5
    else:
        discretionary_score = 2

    # ------------------------------
    # 5. SAVINGS OPPORTUNITY — 15 POINTS
    # ------------------------------

    potential_rate = (potential_saving / income) * 100

    if potential_rate >= 10:
        opportunity_score = 15
    elif potential_rate >= 7:
        opportunity_score = 12
    elif potential_rate >= 5:
        opportunity_score = 9
    elif potential_rate >= 2:
        opportunity_score = 5
    else:
        opportunity_score = 2

    # ------------------------------
    # FINAL SCORE
    # ------------------------------

    total_score = (
        surplus_score
        + savings_score
        + expense_score
        + discretionary_score
        + opportunity_score
    )

    # ------------------------------
    # SCORE CATEGORY
    # ------------------------------

    if total_score >= 80:
        category = "Strong"
    elif total_score >= 60:
        category = "Stable"
    elif total_score >= 40:
        category = "Needs improvement"
    else:
        category = "Needs attention"

    # ------------------------------
    # OUTPUT
    # ------------------------------

    print("\n========================================")
    print(" FINANCIAL HEALTH SCORE")
    print("========================================")

    print(f"\nOverall Score: {total_score}/100")
    print(f"Financial Position: {category}")

    print("\nScore Breakdown:")
    print(f"  Surplus / Deficit: {surplus_score}/25")
    print(f"  Savings Rate: {savings_score}/25")
    print(f"  Expense Burden: {expense_score}/20")
    print(f"  Spending Structure: {discretionary_score}/15")
    print(f"  Savings Opportunity: {opportunity_score}/15")

    print("\nNote:")
    print("This score is based only on the income and")
    print("expenditure information reported to the tool.")
    print("It is an indicative financial-health measure,")
    print("not a professional financial assessment.")

    return {
        'score': total_score,
        'category': category,
        'surplus_score': surplus_score,
        'savings_score': savings_score,
        'expense_score': expense_score,
        'discretionary_score': discretionary_score,
        'opportunity_score': opportunity_score
    }
